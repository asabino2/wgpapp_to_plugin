#!/usr/bin/env python3
"""Convert a Deepy .wgpapp bundle into a WanGP-compatible plugin folder."""

from __future__ import annotations

import json
import re
import shutil
import textwrap
import zipfile
from pathlib import Path, PurePosixPath


def slugify(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", str(value or "deepy-app").lower()).strip("-")
    slug = slug[:48] or "deepy-app"
    return slug


def package_manifest(package_path: Path) -> dict:
    if not package_path.is_file():
        raise FileNotFoundError(f".wgpapp file not found: {package_path}")

    with zipfile.ZipFile(package_path, "r") as archive:
        names = set(archive.namelist())
        if "app.json" not in names:
            raise ValueError(f"The package {package_path.name} does not contain app.json.")

        for member in archive.infolist():
            if member.filename in {"", "/", "\\"}:
                continue
            candidate = PurePosixPath(member.filename)
            if member.filename.startswith(("/", "\\")) or candidate.is_absolute() or ".." in candidate.parts:
                raise ValueError(f"Unsafe file inside the package: {member.filename}")

        manifest = json.loads(archive.read("app.json"))
        if not isinstance(manifest, dict) or not str(manifest.get("name") or "").strip():
            raise ValueError("app.json is missing or does not contain a valid 'name' field.")
        return manifest


def build_plugin_py(app_name: str, plugin_id: str) -> str:
    safe_name = str(app_name).replace("\"", '\\"')
    template = textwrap.dedent(
        """
        import gradio as gr
        from pathlib import Path

        from shared.utils.plugins import WAN2GPPlugin

        PLUGIN_ID = "__PLUGIN_ID__"
        PLUGIN_NAME = "__PLUGIN_NAME__"
        APP_BUNDLE = Path(__file__).resolve().parent / "webapp"
        APP_INDEX = APP_BUNDLE / "index.html"


        class GeneratedDeepyAppPlugin(WAN2GPPlugin):
            def setup_ui(self):
                self.request_global("app")
                self.add_tab(tab_id=PLUGIN_ID, label=PLUGIN_NAME, component_constructor=self.create_app_ui)

            def create_app_ui(self):
                if APP_INDEX.exists():
                    web_url = APP_INDEX.as_uri()
                    html = (
                        '<style>'
                        'html, body { height: 100%; margin: 0; } '
                        'iframe { width: 100%; height: calc(100vh - 160px); border: 0; }'
                        '</style>'
                        f'<iframe src="{web_url}" title="{PLUGIN_NAME}" style="width:100%;height:calc(100vh - 160px);border:0"></iframe>'
                    )
                    return gr.HTML(html)
                return gr.HTML('<div style="padding: 1rem;">The app bundle was not found in <code>' + str(APP_BUNDLE) + '</code>.</div>')
        """
    )
    return template.replace("__PLUGIN_ID__", plugin_id).replace("__PLUGIN_NAME__", safe_name).strip() + "\n"


def generate_plugin(
    package_path: str | Path,
    output_dir: str | Path,
    app_title: str | None = None,
    app_description: str | None = None,
) -> Path:
    source_package = Path(package_path).expanduser().resolve()
    output = Path(output_dir).expanduser().resolve()

    manifest = package_manifest(source_package)
    default_app_name = str(manifest.get("name") or "Deepy App").strip()
    default_description = str(manifest.get("description") or "Deepy app package converted to a WanGP plugin.").strip()
    app_name = (app_title or default_app_name).strip() or default_app_name
    app_description_value = (app_description or default_description).strip() or default_description
    plugin_dir = output
    plugin_dir.mkdir(parents=True, exist_ok=True)

    for stale in ("webapp", "plugin.py", "plugin_info.json", "__init__.py", "README.txt"):
        item = plugin_dir / stale
        if item.is_dir():
            shutil.rmtree(item, ignore_errors=True)
        elif item.exists():
            item.unlink()

    with zipfile.ZipFile(source_package, "r") as archive:
        archive.extractall(plugin_dir / "webapp")

    manifest_path = plugin_dir / "webapp" / "app.json"
    if not manifest_path.is_file():
        raise ValueError("The bundle does not contain app.json after extraction.")

    plugin_id = slugify(f"{app_name}-plugin")
    plugin_info = {
        "name": app_name,
        "author": "Generated by WGPApp to Plugin",
        "version": "1.0.0",
        "description": app_description_value,
        "date": "",
        "wan2gp_version": "",
        "info_card": {
            "tagline": "Deepy app packaged as a WanGP plugin",
            "description": "This plugin was generated from a Deepy .wgpapp bundle and can be installed in WanGP by copying the folder into the plugins directory or by pointing the plugin manager to the GitHub URL.",
            "details": "Converted from a Deepy app bundle.",
        },
    }

    (plugin_dir / "plugin_info.json").write_text(json.dumps(plugin_info, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (plugin_dir / "__init__.py").write_text('"""Generated by WGPApp to Plugin."""\n', encoding="utf-8")
    (plugin_dir / "plugin.py").write_text(build_plugin_py(app_name, plugin_id), encoding="utf-8")

    (plugin_dir / "README.txt").write_text(
        "Plugin generated from a Deepy bundle (.wgpapp).\n\n"
        "Installation:\n"
        "1. Copy this folder into WanGP's plugins subfolder.\n"
        "2. Or use the GitHub URL in WanGP's plugin manager.\n",
        encoding="utf-8",
    )

    return plugin_dir
